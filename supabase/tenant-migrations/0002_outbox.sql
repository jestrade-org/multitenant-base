-- The transactional outbox (§6).
--
-- The event is written in the *same transaction* as the state change that produced it.
-- Publishing directly instead would give two failure modes that both corrupt what the
-- company sees: the transaction commits and the publish fails, so the follow-up work never
-- happens; or the publish succeeds and the transaction rolls back, so someone is notified
-- about a change that does not exist.
--
-- A poller drains this table and hands events to the queue. Delivery is
-- at-least-once, so `published_at` is an optimisation, not a guarantee — consumers
-- deduplicate on event_id.

create table :"schema".outbox_events (
  -- The deduplication key every consumer honours. Generated by the producer, not here,
  -- so a retry of the same unit of work reuses it rather than minting a second event.
  event_id       uuid primary key,

  tenant_id      uuid not null,
  type           text not null,
  occurred_at    timestamptz not null,

  -- IDs and primitives only. An entity reference would not survive the wire, and a full
  -- business record here would put personal data in a table read by every consumer.
  payload        jsonb not null,

  correlation_id text not null,
  causation_id   text,

  -- Publication bookkeeping. Kept alongside the event rather than in a separate table so
  -- claiming a batch is one statement and cannot half-succeed.
  published_at   timestamptz,
  attempts       integer not null default 0,
  last_error     text,
  -- Set while a poller holds this row, so two pollers cannot claim the same event.
  claimed_at     timestamptz,

  created_at     timestamptz not null default now(),

  constraint outbox_events_type_not_empty check (length(type) > 0),
  constraint outbox_events_attempts_not_negative check (attempts >= 0)
);

-- The poller's only query: unpublished, unclaimed, oldest first. A partial index keeps it
-- proportional to the backlog rather than to the history, which is what stops the outbox
-- getting slower every month it stays healthy.
create index outbox_events_pending_idx
  on :"schema".outbox_events (occurred_at)
  where published_at is null;

create index outbox_events_type_idx on :"schema".outbox_events (type);

select app.install_tenant_isolation(:'schema', 'outbox_events');

comment on table :"schema".outbox_events is
  'Transactional outbox. Written with the state change that produced the event; drained '
  'by a poller. At-least-once, so consumers deduplicate on event_id.';
